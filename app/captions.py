SMALL = {'до', 'та', 'і', 'й', 'в', 'у', 'з', 'із', 'на', 'від', 'для', 'по', 'під', 'над', 'за'}


def title(name):
    name = re.sub(r'\s*@\S+', '', name).strip()
    name = re.sub(r'\s+\d+$', '', name)
    out = []
    for i, w in enumerate(name.split()):
        out.append(w if (i and w.lower() in SMALL) else w[:1].upper() + w[1:])
    return ' '.join(out)


def size_text(size):
    return 'd40' if size.startswith('40x40') else size.split('x')[0] + '*' + size.split('x')[1]


def price_text(p):
    return str(int(round(float(p))))


def selection():
    return SELECTION


def news(set_slides):
    """set_slides: [(номер слайда, цена набора)] — слайды с наборами."""
    by = OrderedDict()
    for n, price in set_slides:
        by.setdefault(price_text(price), []).append(n)
    lines = '\n'.join(f'🏷️{p} грн - набір {",".join(map(str, ns))}' for p, ns in by.items())
    return NEWS_HEAD.format(lines=lines)


def reel(info):
    return REEL.format(name=title(info['name']), size=info['size'], price=price_text(info['price']))
